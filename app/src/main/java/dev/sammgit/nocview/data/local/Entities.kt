package dev.sammgit.nocview.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey
import dev.sammgit.nocview.domain.model.Host
import dev.sammgit.nocview.domain.model.HostStatus
import dev.sammgit.nocview.domain.model.Service
import dev.sammgit.nocview.domain.model.ServiceStatus

@Entity(tableName = "hosts")
data class HostEntity(
    @PrimaryKey val name: String,
    val status: String,
    val pluginOutput: String,
    val longPluginOutput: String,
    val perfData: String,
    val stateType: String,
    val lastCheck: Long,
    val nextCheck: Long,
    val lastStateChange: Long,
    val currentAttempt: Int,
    val maxAttempts: Int,
    val acknowledged: Boolean,
    val scheduledDowntimeDepth: Int,
    val isFlapping: Boolean,
    val notificationsEnabled: Boolean,
    val checksEnabled: Boolean,
    val latency: Double,
    val executionTime: Double,
    val lastTimeUp: Long,
    val lastTimeDown: Long,
    val lastTimeUnreachable: Long,
)

@Entity(tableName = "services", primaryKeys = ["hostName", "description"])
data class ServiceEntity(
    val hostName: String,
    val description: String,
    val status: String,
    val pluginOutput: String,
    val longPluginOutput: String,
    val perfData: String,
    val stateType: String,
    val lastCheck: Long,
    val nextCheck: Long,
    val lastStateChange: Long,
    val currentAttempt: Int,
    val maxAttempts: Int,
    val acknowledged: Boolean,
    val scheduledDowntimeDepth: Int,
    val isFlapping: Boolean,
    val notificationsEnabled: Boolean,
    val checksEnabled: Boolean,
    val latency: Double,
    val executionTime: Double,
    val lastTimeOk: Long,
    val lastTimeWarning: Long,
    val lastTimeCritical: Long,
    val lastTimeUnknown: Long,
)

@Entity(tableName = "meta")
data class MetaEntity(
    @PrimaryKey val id: Int = 0,
    val lastUpdated: Long,
    val programVersion: String,
    val hostUp: Int,
    val hostDown: Int,
    val hostUnreachable: Int,
    val hostPending: Int,
    val svcOk: Int,
    val svcWarning: Int,
    val svcCritical: Int,
    val svcUnknown: Int,
    val svcPending: Int,
)

private fun Long.zeroToNull(): Long? = takeIf { it > 0L }

fun HostEntity.toDomain(): Host = Host(
    name = name,
    status = HostStatus.fromApi(status),
    pluginOutput = pluginOutput,
    longPluginOutput = longPluginOutput,
    perfData = perfData,
    stateType = stateType,
    lastCheck = lastCheck.zeroToNull(),
    nextCheck = nextCheck.zeroToNull(),
    lastStateChange = lastStateChange.zeroToNull(),
    currentAttempt = currentAttempt,
    maxAttempts = maxAttempts,
    acknowledged = acknowledged,
    scheduledDowntimeDepth = scheduledDowntimeDepth,
    isFlapping = isFlapping,
    notificationsEnabled = notificationsEnabled,
    checksEnabled = checksEnabled,
    latency = latency,
    executionTime = executionTime,
    lastTimeUp = lastTimeUp.zeroToNull(),
    lastTimeDown = lastTimeDown.zeroToNull(),
    lastTimeUnreachable = lastTimeUnreachable.zeroToNull(),
)

fun Host.toEntity(): HostEntity = HostEntity(
    name = name,
    status = status.name.lowercase(),
    pluginOutput = pluginOutput,
    longPluginOutput = longPluginOutput,
    perfData = perfData,
    stateType = stateType,
    lastCheck = lastCheck ?: 0L,
    nextCheck = nextCheck ?: 0L,
    lastStateChange = lastStateChange ?: 0L,
    currentAttempt = currentAttempt,
    maxAttempts = maxAttempts,
    acknowledged = acknowledged,
    scheduledDowntimeDepth = scheduledDowntimeDepth,
    isFlapping = isFlapping,
    notificationsEnabled = notificationsEnabled,
    checksEnabled = checksEnabled,
    latency = latency ?: 0.0,
    executionTime = executionTime ?: 0.0,
    lastTimeUp = lastTimeUp ?: 0L,
    lastTimeDown = lastTimeDown ?: 0L,
    lastTimeUnreachable = lastTimeUnreachable ?: 0L,
)

